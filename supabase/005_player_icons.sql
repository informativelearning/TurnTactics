create or replace function public.tt_view(p_code text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare r public.tt_rooms%rowtype; s jsonb; mine jsonb; players jsonb; host_view boolean;
begin
if auth.uid() is null then raise exception 'Sign in first'; end if;
select * into r from public.tt_rooms where code=upper(trim(p_code));
if not found then raise exception 'Room unavailable'; end if;
s:=r.state;host_view:=r.host=auth.uid();
select value into mine from jsonb_array_elements(s->'players') where value->>'uid'=auth.uid()::text;
if not host_view and mine is null then raise exception 'Room unavailable';end if;
select coalesce(jsonb_agg(case when host_view or value->>'uid'=auth.uid()::text then value-'uid' else
jsonb_build_object('id',value->'id','name',value->'name','x',value->'x','y',value->'y','alive',value->'alive','icon',value->'icon','isTestSeat',coalesce(value->'isTestSeat','false'::jsonb)) end order by (value->>'id')::int),'[]'::jsonb)
into players from jsonb_array_elements(s->'players');
-- Ballots and account UUIDs never leave the backend. Host log is host-only.
return jsonb_build_object('code',r.code,'isTest',coalesce(s->'isTest','false'::jsonb),'isHost',host_view,'me',mine->'id','phase',s->'phase','day',s->'day','size',s->'size','closed',s->'closed','winner',s->'winner','players',players,'events',s->'events','hostLog',case when host_view then s->'hostLog' else '[]'::jsonb end);
end;$$;



create or replace function public.tt_set_icon(p_code text,p_icon text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare r public.tt_rooms%rowtype;s jsonb;ps jsonb;player jsonb;idx int;image bytea;w int;h int;
begin
if auth.uid() is null then raise exception 'Sign in first';end if;
select * into r from public.tt_rooms where code=upper(trim(p_code)) for update;
if not found then raise exception 'Room unavailable';end if;
s:=r.state;ps:=s->'players';
select (ord-1)::int,value into idx,player from jsonb_array_elements(ps) with ordinality a(value,ord) where value->>'uid'=auth.uid()::text;
if player is null then raise exception 'Only a player can select their own icon';end if;
-- Identical retries are safe, even if the game started after the first save.
if player->>'icon'=p_icon then return public.tt_view(r.code);end if;
if s->>'phase'<>'lobby' then raise exception 'Icons must be selected before the game starts';end if;
if player->>'icon' is not null then raise exception 'Your icon is already locked for this game';end if;
if p_icon is null or length(p_icon)>25000 or p_icon !~ '^data:image/png;base64,[A-Za-z0-9+/]+={0,2}$' then raise exception 'Use a small PNG image generated by the upload control';end if;
image:=decode(substr(p_icon,23),'base64');
if octet_length(image)<33 or octet_length(image)>18000 then raise exception 'Image size not allowed';end if;
if encode(substring(image from 1 for 8),'hex')<>'89504e470d0a1a0a' or encode(substring(image from 9 for 8),'hex')<>'0000000d49484452' then raise exception 'Invalid PNG header';end if;
if get_byte(image,16)<>0 or get_byte(image,17)<>0 or get_byte(image,20)<>0 or get_byte(image,21)<>0 then raise exception 'Image dimensions too large';end if;
w:=get_byte(image,18)*256+get_byte(image,19);h:=get_byte(image,22)*256+get_byte(image,23);
if w<1 or w>64 or h<1 or h>64 then raise exception 'Use an icon no larger than 64 by 64';end if;
player:=player||jsonb_build_object('icon',p_icon);ps:=jsonb_set(ps,array[idx::text],player);s:=jsonb_set(s,'{players}',ps);
update public.tt_rooms set state=s where code=r.code;
return public.tt_view(r.code);
end;$$;
revoke all on function public.tt_view(text),public.tt_set_icon(text,text) from public,anon,authenticated;
grant execute on function public.tt_view(text),public.tt_set_icon(text,text) to authenticated;
commit;
